import { mkdir, readFile, writeFile, rm } from 'node:fs/promises';
import { resolve } from 'node:path';
import { createHash } from 'node:crypto';
import { plugins } from './src/registry';
import { createRuntime, manifest, prefixActions } from './src/runtime';

const check = process.argv.includes('--check');
const destination = resolve(process.argv.slice(2).find(arg => arg !== '--check') ?? '../../core/resources/integrations');
async function emit(path: string, content: string) {
  if (check) {
    if (await readFile(path, 'utf8').catch(() => '') !== content) throw new Error(`Stale plugin artifact: ${path}. Run bun run build.`);
  } else await writeFile(path, content);
}
const hash = (text: string) => createHash('sha256').update(text).digest('hex');
const ids = new Set<string>();
for (const original of plugins) {
  if (!/^[a-z][a-z0-9_]{0,127}$/.test(original.id) || ids.has(original.id)) throw new Error(`Invalid or duplicate plugin ID: ${original.id}`);
  ids.add(original.id);
  const legacy = ['gmail', 'google_calendar'].includes(original.id);
  const plugin = legacy ? prefixActions(original, 'live_') : original;
  createRuntime(plugin); // Compile contracts before replacing artifacts.
  const output = resolve(destination, plugin.id);
  await mkdir(output, { recursive: true });
  const temporary = resolve(import.meta.dir, `.entry-${plugin.id}.ts`);
  const sourceName = original.id.replaceAll('_', '-');
  const setup = `import plugin from './src/providers/${sourceName}';\nimport {createRuntime, prefixActions} from './src/runtime';\nconst descriptor = ${legacy ? "prefixActions(plugin, 'live_')" : 'plugin'};\nexport const rpc = createRuntime(descriptor);\nexport const actionIds = Object.keys(descriptor.actions);\n`;
  await writeFile(temporary, setup + (legacy ? '' : 'serve({rpc});\n'));
  try {
    const compiled = await Bun.build({ entrypoints: [temporary], target: 'bun', minify: true, sourcemap: 'none' });
    if (!compiled.success) throw new AggregateError(compiled.logs, `Build ${plugin.id}`);
    const code = `// Generated by runtime/integrations/build.ts; edit the plugin sources.\n${await compiled.outputs[0].text()}`;
    const entry = legacy ? 'plugin.ts' : 'index.ts';
    await emit(resolve(output, entry), code);
    let definition: any = manifest(plugin);
    if (legacy) {
      const previous = JSON.parse(await readFile(resolve(import.meta.dir, '../../core/resources/integrations', plugin.id, 'manifest.json'), 'utf8'));
      definition = { ...previous, version: plugin.version, userAuth: { ...definition.userAuth, plugin: { ...definition.userAuth.plugin, legacySync: true } }, configSchema: { ...definition.configSchema, properties: { ...previous.configSchema.properties, ...definition.configSchema.properties } }, actions: [...previous.actions.filter((a: any) => !a.id.startsWith('live_')), ...definition.actions] };
    } else {
      await emit(resolve(output, 'package.json'), JSON.stringify({ name: `rootcx-integration-${plugin.id}`, version: plugin.version, private: true, type: 'module' }, null, 2) + '\n');
    }
    await emit(resolve(output, 'THIRD_PARTY_NOTICES.md'), await readFile(resolve(import.meta.dir, 'THIRD_PARTY_NOTICES.md'), 'utf8'));
    const raw = JSON.stringify(definition, null, 2) + '\n';
    await emit(resolve(output, 'manifest.json'), raw);
    await emit(resolve(output, 'plugin-lock.json'), JSON.stringify({ protocolVersion: 1, version: plugin.version, artifacts: { [entry]: hash(code), 'manifest.json': hash(raw) } }, null, 2) + '\n');
    console.log(`${plugin.id}@${plugin.version}: ${Object.keys(plugin.actions).length} actions; live qualification pending`);
  } finally { await rm(temporary, { force: true }); }
}
